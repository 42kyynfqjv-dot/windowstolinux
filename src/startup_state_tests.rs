use super::*;

struct Fixture {
    s: Startup,
    m: Module,
    t: Thread,
    p: Pointer,
    h: Pointer,
    e: Encoded,
}
fn fixture() -> Fixture {
    let mut s = Startup::new().unwrap();
    let m = s
        .map_module((0x4000, &[0xc3; 32]), (0x5000, &[0; 32]), 0x6000)
        .unwrap();
    let t = s.bind_empty_thread(0x8000, 256).unwrap();
    s.establish_cookie(m, 0xa5a5a5a5).unwrap();
    let h = s.module_pointer(m, 0x4000, true).unwrap();
    let scope = s.module_pointer(m, 0x5000, false).unwrap();
    let e = s.encode(m, scope).unwrap();
    let p = s.stack_pointer(t, 0x8040).unwrap();
    Fixture { s, m, t, p, h, e }
}
fn record(f: &mut Fixture, p: Pointer, previous: Option<Pointer>) {
    let guard = f.s.stack_pointer(f.t, p.address - 36).unwrap();
    let frame = f.s.offset(p, 16).unwrap();
    f.s.store_guard(guard, f.m, frame).unwrap();
    match previous {
        Some(prev) => f.s.store_pointer(p, prev).unwrap(),
        None => f.s.write(p, &u32::MAX.to_le_bytes()).unwrap(),
    }
    f.s.store_pointer(f.s.offset(p, 4).unwrap(), f.h).unwrap();
    f.s.store_encoded(f.s.offset(p, 8).unwrap(), f.e).unwrap();
    f.s.write(f.s.offset(p, 12).unwrap(), &0xffff_fffeu32.to_le_bytes())
        .unwrap();
}

#[test]
fn literal_record_bytes_and_nested_normal_cleanup() {
    let mut f = fixture();
    let p = f.p;
    record(&mut f, p, None);
    // Literal independent little-endian vector; not generated by record encoding.
    assert_eq!(
        f.s.read(p, 16).unwrap(),
        &[255, 255, 255, 255, 0, 64, 0, 0, 165, 245, 165, 165, 254, 255, 255, 255]
    );
    f.s.register(f.t, p, f.m, f.h, f.e).unwrap();
    let next = f.s.offset(p, 32).unwrap();
    record(&mut f, next, Some(p));
    f.s.register(f.t, next, f.m, f.h, f.e).unwrap();
    assert_eq!(f.s.restore(f.t, p), Err(Error::Identity));
    assert_eq!(f.s.retire_thread(f.t), Err(Error::Active));
    assert_eq!(f.s.establish_cookie(f.m, 0), Err(Error::Active));
    f.s.restore(f.t, next).unwrap();
    f.s.restore(f.t, p).unwrap();
    f.s.retire_thread(f.t).unwrap();
    assert!(f.s.read(p, 4).is_err());
}

#[test]
fn original_prolog_offsets_match_literal_stack_trace() {
    // Independently track the stack of the retained 0x475ba0 instruction sequence.
    // S=0x8100 before push14,pushscope,call. Callee entry E=S-12.
    // pushhandler,pushFS -> E-8. EBP=E+8. sub20,push3regs,pushguard
    // leaves ESP=E-44. pushreturn,ret restores that ESP. No code is admitted.
    let initial = 0x8100u32;
    let entry = initial - 12;
    let ebp = entry + 8;
    let record_address = ebp - 16;
    let saved_sp_address = ebp - 24;
    let guard_address = entry - 44;
    assert_eq!(
        (entry, ebp, record_address, saved_sp_address, guard_address),
        (0x80f4, 0x80fc, 0x80ec, 0x80e4, 0x80c8)
    );
    let mut f = fixture();
    let p = f.s.stack_pointer(f.t, record_address).unwrap();
    record(&mut f, p, None);
    let guard = f.s.stack_pointer(f.t, guard_address).unwrap();
    f.s.store_guard(guard, f.m, f.s.stack_pointer(f.t, ebp).unwrap())
        .unwrap(); // cookie XOR EBP
    let saved = f.s.stack_pointer(f.t, saved_sp_address).unwrap();
    f.s.store_pointer(saved, guard).unwrap();
    f.s.register(f.t, p, f.m, f.h, f.e).unwrap();
    assert_eq!(f.s.read(guard, 4).unwrap(), &[0x59, 0x25, 0xa5, 0xa5]);
    assert_eq!(f.s.read(saved, 4).unwrap(), &[0xc8, 0x80, 0, 0]);
    // This does not prove guard validation, scope semantics or original handlers.
    f.s.restore(f.t, p).unwrap();
}

#[test]
fn bytes_without_pointer_provenance_never_register() {
    let mut f = fixture();
    let p = f.p;
    let bytes = [
        255, 255, 255, 255, 0, 64, 0, 0, 165, 245, 165, 165, 254, 255, 255, 255,
    ];
    f.s.write(p, &bytes).unwrap();
    assert_eq!(f.s.register(f.t, p, f.m, f.h, f.e), Err(Error::Unknown));
    record(&mut f, p, None);
    // Even an equal partial-byte write removes the encoded pointer relation.
    f.s.write(f.s.offset(p, 9).unwrap(), &[245]).unwrap();
    assert_eq!(f.s.register(f.t, p, f.m, f.h, f.e), Err(Error::Unknown));
}

#[test]
fn initialization_complete_range_permissions_and_atomic_failed_mapping() {
    let mut f = fixture();
    let p = f.p;
    assert_eq!(f.s.read(p, 4), Err(Error::Memory(Fault::Uninitialized)));
    let end = f.s.stack_pointer(f.t, 0x80fe).unwrap();
    assert_eq!(
        f.s.write(end, &[1, 2, 3, 4]),
        Err(Error::Memory(Fault::Range))
    );
    assert_eq!(f.s.write(f.h, &[0]), Err(Error::Memory(Fault::Permission)));
    assert_eq!(
        f.s.map_module((0x7000, &[0xc3]), (0x7100, &[0; 4]), 0x6000),
        Err(Error::Memory(Fault::Overlap))
    );
    // Rollback leaves both earlier maps free; original module remains intact.
    f.s.map_module((0x7000, &[0xc3]), (0x7100, &[0; 4]), 0x7200)
        .unwrap();
    record(&mut f, p, None);
    f.s.register(f.t, p, f.m, f.h, f.e).unwrap();
}

#[test]
fn process_thread_and_module_identity_not_numeric_coincidence() {
    let mut a = fixture();
    let b = fixture();
    let p = a.p;
    assert_eq!(
        a.s.store_pointer(p, b.h),
        Err(Error::Memory(Fault::Identity))
    );
    record(&mut a, p, None);
    let other = a.s.bind_empty_thread(0x9000, 256).unwrap();
    assert_eq!(a.s.register(other, p, a.m, a.h, a.e), Err(Error::Identity));
    let m =
        a.s.map_module((0x10000, &[0xc3]), (0x11000, &[0; 4]), 0x12000)
            .unwrap();
    a.s.establish_cookie(m, 0xa5a5a5a5).unwrap();
    assert_eq!(a.s.register(a.t, p, m, a.h, a.e), Err(Error::Identity));
    assert_eq!(a.s.encode(m, a.e.target), Err(Error::Identity));
    assert_eq!(a.s.register(b.t, p, a.m, a.h, a.e), Err(Error::Identity));
}

#[test]
fn cookie_generation_and_stack_reuse_invalidate_old_relations() {
    let mut f = fixture();
    let p = f.p;
    f.s.establish_cookie(f.m, 0xa5a5a5a5).unwrap();
    assert_eq!(f.s.store_encoded(p, f.e), Err(Error::Corrupt));
    f.s.retire_thread(f.t).unwrap();
    f.s.bind_empty_thread(0x8000, 256).unwrap();
    assert_eq!(f.s.write(p, &[0; 4]), Err(Error::Memory(Fault::Stale)));
}

#[test]
fn active_alias_write_and_unknown_external_effect_block_continuation() {
    for external in [false, true] {
        let mut f = fixture();
        let p = f.p;
        record(&mut f, p, None);
        f.s.register(f.t, p, f.m, f.h, f.e).unwrap();
        if external {
            f.s.unknown_external_effect();
        } else {
            f.s.write(p, &[255]).unwrap();
        }
        assert_eq!(f.s.read(p, 4), Err(Error::Pending));
        assert_eq!(f.s.restore(f.t, p), Err(Error::Pending));
        assert_eq!(f.s.write(p, &[0]), Err(Error::Pending));
        assert_eq!(f.s.establish_cookie(f.m, 1), Err(Error::Pending));
        assert_eq!(f.s.bind_empty_thread(0x9000, 64), Err(Error::Pending));
        assert_eq!(f.s.retire_thread(f.t), Err(Error::Pending));
    }
}

#[test]
fn exception_snapshot_is_validated_search_order_not_permission_to_unwind() {
    let mut f = fixture();
    let p = f.p;
    record(&mut f, p, None);
    f.s.register(f.t, p, f.m, f.h, f.e).unwrap();
    let next = f.s.offset(p, 32).unwrap();
    f.h = f.s.module_pointer(f.m, 0x4001, true).unwrap();
    record(&mut f, next, Some(p));
    f.s.register(f.t, next, f.m, f.h, f.e).unwrap();
    assert_eq!(
        f.s.begin_exception(f.t, 0xe0420001, false).unwrap(),
        Dispatch {
            code: 0xe0420001,
            continuable: false,
            handlers: vec![0x4001, 0x4000]
        }
    );
    assert_eq!(f.s.restore(f.t, next), Err(Error::Pending));
    assert_eq!(f.s.read(p, 4), Err(Error::Pending));
    assert_eq!(f.s.offset(p, 1), Err(Error::Pending));
    // There is intentionally no "handled" Boolean or resume API.
}

#[test]
fn complete_entropy_outputs_preserve_neighbors_and_unknown_call_state() {
    let mut f = fixture();
    let p = f.p;
    f.s.write(p, &[0xcc; 16]).unwrap();
    let out = f.s.offset(p, 4).unwrap();
    let effects =
        f.s.entropy_output(f.t, out, EntropyOutput::FileTime(0x0123456789abcdef))
            .unwrap();
    assert_eq!(
        f.s.read(p, 16).unwrap(),
        &[
            0xcc, 0xcc, 0xcc, 0xcc, 0xef, 0xcd, 0xab, 0x89, 0x67, 0x45, 0x23, 0x01, 0xcc, 0xcc,
            0xcc, 0xcc
        ]
    );
    assert_eq!(
        effects,
        CallEffects {
            eax: None,
            volatile_registers_known: false,
            flags_known: false,
            last_error_known: false
        }
    );
    assert_eq!(
        f.s.entropy_output(
            f.t,
            out,
            EntropyOutput::PerformanceCounter {
                counter: -2,
                success: 0x80000000
            }
        )
        .unwrap()
        .eax,
        Some(0x80000000)
    );
    assert_eq!(
        f.s.read(out, 8).unwrap(),
        &[254, 255, 255, 255, 255, 255, 255, 255]
    );
    let short = f.s.stack_pointer(f.t, 0x80fc).unwrap();
    assert_eq!(
        f.s.entropy_output(f.t, short, EntropyOutput::FileTime(0)),
        Err(Error::Memory(Fault::Range))
    );
    let other = f.s.bind_empty_thread(0x9000, 64).unwrap();
    assert_eq!(
        f.s.entropy_output(other, out, EntropyOutput::FileTime(0)),
        Err(Error::Identity)
    );
}

