#[test]
fn range_check_does_not_invent_initialization_or_cross_mapping_authority() {
    let mut s = Space::new(64, 4).unwrap();
    let a = s
        .map(0x1000, 4, Owner::Stack(1), Permissions::READ_WRITE, false)
        .unwrap();
    let b = s
        .map(0x1004, 4, Owner::Stack(1), Permissions::READ_WRITE, false)
        .unwrap();
    assert_eq!(s.validate_range(a, Owner::Stack(1), 0x1000, 4), Ok(()));
    assert_eq!(s.read(0x1000, 4), Err(Fault::Uninitialized));
    assert_eq!(
        s.validate_range(a, Owner::Stack(1), 0x1004, 4),
        Err(Fault::Identity)
    );
    assert_eq!(
        s.validate_range(a, Owner::Stack(1), 0x1002, 4),
        Err(Fault::Range)
    );
    s.release(b, Owner::Stack(1)).unwrap();
    assert_eq!(
        s.validate_range(b, Owner::Stack(1), 0x1004, 4),
        Err(Fault::Stale)
    );
}

#[test]
fn saved_guard_corruption_and_unloaded_module_never_authorize_cleanup() {
    let mut f = fixture();
    let p = f.p;
    record(&mut f, p, None);
    let guard = f.s.stack_pointer(f.t, p.address - 36).unwrap();
    f.s.write(guard, &[0; 4]).unwrap();
    assert_eq!(f.s.register(f.t, p, f.m, f.h, f.e), Err(Error::Unknown));
    record(&mut f, p, None);
    f.s.register(f.t, p, f.m, f.h, f.e).unwrap();
    assert_eq!(f.s.retire_module(f.m), Err(Error::Active));
    f.s.write(guard, &[0]).unwrap();
    assert_eq!(f.s.restore(f.t, p), Err(Error::Pending));
    let mut f = fixture();
    let p = f.p;
    f.s.retire_module(f.m).unwrap();
    assert_eq!(f.s.store_pointer(p, f.h), Err(Error::Memory(Fault::Stale)));
    assert_eq!(f.s.store_encoded(p, f.e), Err(Error::Identity));
}

#[test]
fn uncontracted_counter_failure_is_not_success_or_initialized_output() {
    let mut f = fixture();
    let p = f.p;
    assert_eq!(
        f.s.entropy_output(
            f.t,
            p,
            EntropyOutput::PerformanceCounter {
                counter: 42,
                success: 0
            }
        ),
        Err(Error::Unknown)
    );
    assert_eq!(f.s.read(p, 8), Err(Error::Memory(Fault::Uninitialized)));
    // Wrong-thread request has no memory side effects either.
    let t = f.s.bind_empty_thread(0x9000, 64).unwrap();
    assert_eq!(
        f.s.entropy_output(
            t,
            p,
            EntropyOutput::PerformanceCounter {
                counter: 42,
                success: 1
            }
        ),
        Err(Error::Identity)
    );
    assert_eq!(f.s.read(p, 8), Err(Error::Memory(Fault::Uninitialized)));
}

#[test]
fn exception_rechecks_backing_bytes_before_exposing_handler_addresses() {
    // Bypass the public invalidating write only as adversarial test injection:
    // stale metadata must not substitute for actual record and guard bytes.
    for offset in [0i32, 4, 8, 12, -36] {
        let mut f = fixture();
        let p = f.p;
        record(&mut f, p, None);
        f.s.register(f.t, p, f.m, f.h, f.e).unwrap();
        let at = (i64::from(p.address) + i64::from(offset)) as u32;
        let old = f.s.memory.read(at, 1).unwrap()[0];
        f.s.memory.write(at, &[old ^ 1]).unwrap();
        assert_eq!(
            f.s.begin_exception(f.t, 0xe0420001, true),
            Err(Error::Corrupt)
        );
        assert_eq!(f.s.read(p, 4), Err(Error::Pending));
        assert_eq!(f.s.restore(f.t, p), Err(Error::Pending));
    }
}
